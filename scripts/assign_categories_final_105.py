@transaction.atomic
def assign_final_105():
    """Назначает категории для оставшихся 105 ингредиентов"""
    print("=" * 70)
    print("📂 ФИНАЛЬНОЕ НАЗНАЧЕНИЕ КАТЕГОРИЙ (105)")
    print("=" * 70)

    without_cat = Ingredient.objects.filter(category__isnull=True)
    total = without_cat.count()

    if total == 0:
        print("✅ Все ингредиенты имеют категории!")
        return

    print(f"Осталось ингредиентов без категории: {total}")
    print("=" * 70)

    stats = {
        'assigned': 0,
        'not_found': 0,
    }

    # Создаем все категории из маппинга
    categories_to_create = set(FINAL_105_MAP.values())
    for category_name in categories_to_create:
        IngredientCategory.objects.get_or_create(name=category_name)

    # Список нераспознанных
    not_found_list = []

    for ing in without_cat:
        ing_lower = ing.name.lower()
        assigned = False

        # Ищем по ключевым словам
        for keyword, category_name in FINAL_105_MAP.items():
            if keyword in ing_lower:
                try:
                    category = IngredientCategory.objects.get(name=category_name)
                    ing.category = category
                    ing.save()
                    stats['assigned'] += 1
                    assigned = True
                    break
                except IngredientCategory.DoesNotExist:
                    # Создаем категорию если не существует
                    category = IngredientCategory.objects.create(name=category_name)
                    ing.category = category
                    ing.save()
                    stats['assigned'] += 1
                    assigned = True
                    break

        if not assigned:
            stats['not_found'] += 1
            not_found_list.append(ing.name)

    # Итог
    print("\n" + "=" * 70)
    print("📊 СТАТИСТИКА")
    print("=" * 70)
    print(f"  Всего оставалось: {total}")
    print(f"  Назначено категорий: {stats['assigned']}")
    print(f"  Осталось без категории: {stats['not_found']}")
    print("=" * 70)

    if stats['not_found'] > 0:
        print("\n⚠️ Ингредиенты без категории:")
        for name in not_found_list:
            print(f"  - {name}")

        # Сохраняем список в файл
        with open('no_category_final_105.txt', 'w', encoding='utf-8') as f:
            for name in not_found_list:
                f.write(f"{name}\n")

        print(f"\n💡 Список сохранен в no_category_final_105.txt")
    else:
        print("\n🎉 ВСЕ ИНГРЕДИЕНТЫ ИМЕЮТ КАТЕГОРИИ!")


if __name__ == "__main__":
    assign_final_105()