@transaction.atomic
def rebuild_categories():
    """Перестраивает категории по новому классификатору"""
    print("=" * 70)
    print("🔄 ПЕРЕСТРОЙКА КАТЕГОРИЙ")
    print("=" * 70)

    stats = {
        'categories_created': 0,
        'categories_moved': 0,
        'categories_deleted': 0,
        'ingredients_updated': 0,
    }

    # Сначала создаем все родительские категории
    for parent_name, children in CATEGORY_STRUCTURE.items():
        parent, created = IngredientCategory.objects.get_or_create(
            name=parent_name,
            defaults={'parent': None}
        )
        if created:
            stats['categories_created'] += 1
            print(f"✅ Создана: {parent_name}")

    # Затем создаем подкатегории и перемещаем ингредиенты
    for parent_name, children in CATEGORY_STRUCTURE.items():
        parent = IngredientCategory.objects.get(name=parent_name)

        for subcat_name, ingredient_names in children.items():
            subcat, created = IngredientCategory.objects.get_or_create(
                name=subcat_name,
                defaults={'parent': parent}
            )
            if created:
                stats['categories_created'] += 1
                print(f"  ✅ {subcat_name}")
            elif subcat.parent != parent:
                subcat.parent = parent
                subcat.save()
                stats['categories_moved'] += 1

            # Находим ингредиенты для этой подкатегории
            for ing_name in ingredient_names:
                # Ищем точное совпадение или частичное
                ingredients = AbstractIngredient.objects.filter(
                    name__icontains=ing_name
                ).exclude(category=subcat)

                # Если точное совпадение — берем его
                exact_match = ingredients.filter(name=ing_name).first()
                if exact_match:
                    exact_match.category = subcat
                    exact_match.save()
                    stats['ingredients_updated'] += 1
                    continue

                # Иначе берем все совпадения
                for ing in ingredients:
                    ing.category = subcat
                    ing.save()
                    stats['ingredients_updated'] += 1

    print("\n" + "=" * 70)
    print("📊 СТАТИСТИКА")
    print("=" * 70)
    print(f"  Создано категорий: {stats['categories_created']}")
    print(f"  Перемещено категорий: {stats['categories_moved']}")
    print(f"  Обновлено ингредиентов: {stats['ingredients_updated']}")
    print("=" * 70)


if __name__ == "__main__":
    rebuild_categories()