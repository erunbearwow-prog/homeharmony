@transaction.atomic
def assign_categories():
    """Назначает категории ингредиентам без категории"""
    print("=" * 70)
    print("📂 НАЗНАЧЕНИЕ КАТЕГОРИЙ")
    print("=" * 70)

    without_cat = Ingredient.objects.filter(category__isnull=True)
    total = without_cat.count()

    if total == 0:
        print("✅ Все ингредиенты имеют категории!")
        return

    print(f"Найдено ингредиентов без категории: {total}")
    print("=" * 70)

    stats = {
        'assigned': 0,
        'not_found': 0,
        'category_created': 0,
    }

    # Создаем все категории из маппинга заранее
    categories_to_create = set(CATEGORY_MAP.values())
    for category_name in categories_to_create:
        IngredientCategory.objects.get_or_create(name=category_name)

    # Обрабатываем каждый ингредиент
    for i, ing in enumerate(without_cat, 1):
        ing_lower = ing.name.lower()
        assigned = False

        # Ищем по ключевым словам
        for keyword, category_name in CATEGORY_MAP.items():
            if keyword in ing_lower:
                try:
                    category = IngredientCategory.objects.get(name=category_name)
                    ing.category = category
                    ing.save()
                    stats['assigned'] += 1
                    assigned = True
                    break
                except IngredientCategory.DoesNotExist:
                    # Создаем категорию если не существует
                    category = IngredientCategory.objects.create(name=category_name)
                    stats['category_created'] += 1
                    ing.category = category
                    ing.save()
                    stats['assigned'] += 1
                    assigned = True
                    break

        if not assigned:
            stats['not_found'] += 1

        # Прогресс
        if i % 100 == 0:
            print(f"📊 Прогресс: {i}/{total} | Назначено: {stats['assigned']}")

    # Итог
    print("\n" + "=" * 70)
    print("📊 СТАТИСТИКА")
    print("=" * 70)
    print(f"  Всего ингредиентов без категории: {total}")
    print(f"  Назначено категорий: {stats['assigned']}")
    print(f"  Создано новых категорий: {stats['category_created']}")
    print(f"  Осталось без категории: {stats['not_found']}")
    print("=" * 70)

    if stats['not_found'] > 0:
        print("\n⚠️ Ингредиенты без категории (первые 20):")
        for ing in Ingredient.objects.filter(category__isnull=True)[:20]:
            print(f"  - {ing.name}")

        print(f"\n💡 Рекомендация: проверьте эти ингредиенты вручную")
        print(f"   или добавьте ключевые слова в CATEGORY_MAP")


if __name__ == "__main__":
    assign_categories()