class Command(BaseCommand):
    help = 'Синхронизирует справочник утвари (RecommendedUtensil): обновляет существующие, создаёт отсутствующие, переименовывает по former_names'

    def handle(self, *args, **options):
        updated, created, errors = [], [], []

        for name, data in UTENSILS.items():
            code = data.get('code')
            try:
                obj = None
                if code:
                    obj = RecommendedUtensil.objects.filter(code=code).first()
                if obj is None:
                    obj = RecommendedUtensil.objects.filter(name=name).first()
                if obj is None:
                    for former in data.get('former_names', []):
                        obj = RecommendedUtensil.objects.filter(name=former).first()
                        if obj:
                            break

                if obj is None:
                    RecommendedUtensil.objects.create(name=name, **data)
                    created.append(name)
                    continue

                changed = []
                for field, value in data.items():
                    if field == 'former_names':
                        continue  # не поле модели
                    if getattr(obj, field) != value:
                        setattr(obj, field, value)
                        changed.append(field)

                if obj.name != name:
                    obj.name = name
                    changed.append('name')

                if changed:
                    obj.save(update_fields=changed)
                    updated.append(f'{name}: {", ".join(changed)}')

            except Exception as e:
                errors.append(f'{name}: {e}')

        self.stdout.write(self.style.SUCCESS(f'Обновлено записей: {len(updated)}'))
        for line in updated:
            self.stdout.write(f'  {line}')
        if created:
            self.stdout.write(self.style.SUCCESS(f'Создано записей: {len(created)}'))
            for line in created:
                self.stdout.write(f'  + {line}')
        if errors:
            self.stdout.write(self.style.ERROR(f'Ошибок: {len(errors)}'))
            for line in errors:
                self.stdout.write(f'  {line}')
