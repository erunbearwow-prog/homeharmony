        self.stdout.write("🔗 Привязываем AbstractIngredient к категориям...")

        lines = classifier_text.splitlines()
        stack = []  # (level, category_name)
        updated_count = 0
        not_found_count = 0
        skip_count = 0

        with transaction.atomic():
            for raw_line in lines:
                line = raw_line.rstrip()
                if not line:
                    continue

                stripped = line.lstrip()
                indent = len(line) - len(stripped)
                level = indent // 4

                # Проверяем, что это ингредиент (начинается с дефиса или без отступа с названием)
                # В нашем классификаторе ингредиенты — это строки без кодов, но с отступом
                # и без дефиса (так как мы убрали дефисы в чистом классификаторе)

                # Пропускаем строки, которые являются названиями категорий (они не содержат дефис и имеют отступ)
                # Но нам нужно понять, где категория, а где ингредиент
                # Ингредиенты — это самые глубокие элементы (у них нет детей)

                # Простая стратегия: сохраняем все строки в стек, и если следующая строка имеет
                # меньший уровень, то текущая строка — это ингредиент
                # Но проще: мы знаем, что ингредиенты — это строки, которые не содержат дефис,
                # но имеют отступ и не являются категориями

                # Пропускаем строки с кодом (у нас их нет)
                if re.match(r'^\d', stripped):
                    continue

                # Если строка начинается с дефиса — это ингредиент
                if stripped.startswith('-'):
                    ingredient_name = stripped[1:].strip()
                    # Находим родительскую категорию из стека
                    if stack:
                        parent_name = stack[-1][1]
                        try:
                            parent_cat = IngredientCategory.objects.get(name=parent_name)
                            # Ищем ингредиент по имени
                            try:
                                ing = AbstractIngredient.objects.get(name=ingredient_name)
                                if ing.category != parent_cat:
                                    ing.category = parent_cat
                                    ing.save(update_fields=['category'])
                                    updated_count += 1
                                    self.stdout.write(
                                        self.style.SUCCESS(
                                            f'✅ {ingredient_name} → {parent_name}'
                                        )
                                    )
                                else:
                                    skip_count += 1
                            except AbstractIngredient.DoesNotExist:
                                self.stdout.write(
                                    self.style.WARNING(f'⚠️ Ингредиент не найден: {ingredient_name}')
                                )
                                not_found_count += 1
                        except IngredientCategory.DoesNotExist:
                            self.stdout.write(
                                self.style.WARNING(f'⚠️ Категория не найдена: {parent_name}')
                            )
                            not_found_count += 1
                    continue

                # Если строка не начинается с дефиса — это категория
                # Убираем уточнения в скобках для поиска
                clean_name = re.sub(r'\s*\(.*?\)\s*$', '', stripped).strip()
                if not clean_name:
                    clean_name = stripped

                # Обновляем стек
                while stack and stack[-1][0] >= level:
                    stack.pop()
                stack.append((level, clean_name))

