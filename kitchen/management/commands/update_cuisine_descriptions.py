# kitchen/management/commands/update_cuisine_descriptions.py

from django.core.management.base import BaseCommand
from kitchen.models import Cuisine


class Command(BaseCommand):
    help = 'Добавляет описания для кухонь'

    def handle(self, *args, **options):
        descriptions = {
            'Азиатская': 'Кухня стран Восточной, Юго-Восточной и Центральной Азии. Характерны рис, лапша, соевый соус, имбирь, чеснок и пряные травы.',
            'Африканская': 'Кухня народов Африканского континента. Используются кускус, ямс, бананы, арахис, пальмовое масло и пряные специи.',
            'Европейская': 'Объединяет кулинарные традиции стран Европы. Характерны мясные и рыбные блюда, соусы, свежие овощи и фрукты.',
            'Кавказская': 'Кухня народов Кавказа. Характерны мясные блюда (шашлык, долма), сыры, зелень, пряности и овощи.',
            'Скандинавская': 'Кухня стран Северной Европы. Характерны рыба, морепродукты, ржаной хлеб, ягоды и картофель.',
            'Средиземноморская': 'Кухня стран Средиземноморья. Характерны оливковое масло, овощи, рыба, морепродукты, сыры и травы.',
            'Балканская': 'Кухня стран Балканского полуострова. Характерны мясные блюда, сыры, перец, йогурт и паприка.',
            'Ближневосточная': 'Кухня арабских стран и Израиля. Характерны нут, хумус, фалафель, оливки, финики и йогурт.',
            'Латиноамериканская': 'Кухня стран Латинской Америки. Характерны кукуруза, фасоль, перец, авокадо и тропические фрукты.',
        }

        for name, description in descriptions.items():
            cuisine = Cuisine.objects.filter(name=name).first()
            if cuisine:
                cuisine.description = description
                cuisine.save()
                self.stdout.write(f"✅ {name}: описание добавлено")