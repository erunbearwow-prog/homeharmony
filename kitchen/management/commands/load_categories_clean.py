        self.stdout.write("🚀 Загружаем категории из чистого классификатора...")

        lines = classifier_text.splitlines()
        stack = []  # (level, name)
        created_count = 0
        existing_count = 0

        with transaction.atomic():
            for raw_line in lines:
                line = raw_line.rstrip()
                if not line:
                    continue

                stripped = line.lstrip()
                indent = len(line) - len(stripped)
                level = indent // 4

                # Проверяем, что это не ингредиент (начинается с дефиса)
                if stripped.startswith('-'):
                    continue

                name = stripped.strip()
                if not name:
                    continue

                # Находим родителя
                parent = None
                if level > 0:
                    for i in range(len(stack) - 1, -1, -1):
                        if stack[i][0] == level - 1:
                            parent_name = stack[i][1]
                            try:
                                parent = IngredientCategory.objects.get(name=parent_name)
                            except IngredientCategory.DoesNotExist:
                                self.stdout.write(
                                    self.style.WARNING(
                                        f'⚠️ Родитель "{parent_name}" не найден для "{name}"'
                                    )
                                )
                            break

                # Создаем категорию
                try:
                    cat = IngredientCategory.objects.get(name=name)
                    existing_count += 1
                    if cat.parent != parent:
                        cat.parent = parent
                        cat.save(update_fields=['parent'])
                        self.stdout.write(
                            self.style.SUCCESS(
                                f'✅ Обновлена: {name} → {parent.name if parent else "КОРЕНЬ"}'
                            )
                        )
                except IngredientCategory.DoesNotExist:
                    cat = IngredientCategory.objects.create(
                        name=name,
                        parent=parent,
                        sort_order=0
                    )
                    created_count += 1
                    self.stdout.write(
                        self.style.SUCCESS(
                            f'✅ Создана: {name} → {parent.name if parent else "КОРЕНЬ"}'
                        )
                    )

                # Обновляем стек
                while stack and stack[-1][0] >= level:
                    stack.pop()
                stack.append((level, name))

            self.stdout.write(self.style.SUCCESS(
                f'\n✨ Готово! Создано: {created_count}, уже существовало: {existing_count}'
            ))