# Вливаем списки в METHODS. setdefault не затирает utensil_names,
# если они уже заданы внутри самой записи метода.
for _method_name, _utensils in METHOD_UTENSILS.items():
    if _method_name in METHODS:
        METHODS[_method_name].setdefault('utensil_names', _utensils)
    else:
        raise SystemExit(f'METHOD_UTENSILS: метод "{_method_name}" не найден в METHODS — проверь название')


class Command(BaseCommand):
    help = 'Синхронизирует справочник способов обработки (CookingMethod): обновляет существующие, создаёт отсутствующие; валидирует маркеры утвари и проставляет M2M-связи'

    def handle(self, *args, **options):
        updated, created, errors = [], [], []
        utensil_names = set(RecommendedUtensil.objects.values_list('name', flat=True))

        for name, data in METHODS.items():
            code = data.get('code')
            try:
                extra_names = data.get('utensil_names', [])

                obj = None
                if code:
                    obj = CookingMethod.objects.filter(code=code).first()
                if obj is None:
                    obj = CookingMethod.objects.filter(name=name).first()

                if obj is None:
                    # при создании utensil_names в модель не передаём
                    obj = CookingMethod.objects.create(
                        name=name,
                        **{k: v for k, v in data.items() if k != 'utensil_names'}
                    )
                    created.append(name)
                else:
                    changed = []
                    for field, value in data.items():
                        if field == 'utensil_names':
                            continue  # не поле модели
                        if getattr(obj, field) != value:
                            setattr(obj, field, value)
                            changed.append(field)

                    if obj.name != name:
                        obj.name = name
                        changed.append('name')

                    if changed:
                        obj.save(update_fields=changed)
                        updated.append(f'{name}: {", ".join(changed)}')

                # --- Валидация: маркеры в description и явный список ---
                description = data.get('description', '')
                marker_names = [
                    m.group(1).strip()
                    for m in UTENSIL_MARKER_RE.finditer(description)
                ]
                for ut_name in marker_names:
                    if ut_name not in utensil_names:
                        self.stdout.write(self.style.WARNING(
                            f'{name}: в description маркер на несуществующую утварь: {ut_name}'))
                for ut_name in extra_names:
                    if ut_name not in utensil_names:
                        self.stdout.write(self.style.WARNING(
                            f'{name}: в utensil_names несуществующая утварь: {ut_name}'))

                # --- Связи: маркеры + utensil_names, безусловно ---
                # set() вызывается даже при пустом all_names:
                # убранная из словаря утварь исчезает из связей при следующем прогоне
                all_names = set(marker_names) | set(extra_names)
                obj.recommended_utensils.set(
                    RecommendedUtensil.objects.filter(name__in=all_names))

            except Exception as e:
                errors.append(f'{name}: {e}')

        self.stdout.write(self.style.SUCCESS(f'Обновлено записей: {len(updated)}'))
        for line in updated:
            self.stdout.write(f'  {line}')
        if created:
            self.stdout.write(self.style.SUCCESS(f'Создано записей: {len(created)}'))
            for line in created:
                self.stdout.write(f'  + {line}')
        if errors:
            self.stdout.write(self.style.ERROR(f'Ошибок: {len(errors)}'))
            for line in errors:
                self.stdout.write(f'  {line}')
