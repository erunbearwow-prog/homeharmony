def import_ingredients():
    """Главная функция импорта."""
    if not os.path.exists(HTML_FOLDER):
        print(f"❌ Папка {HTML_FOLDER} не найдена!")
        return

    html_files = glob.glob(os.path.join(HTML_FOLDER, 'food_*.html'))
    html_files += glob.glob(os.path.join(HTML_FOLDER, 'food_*.htm'))

    if not html_files:
        print(f"❌ Файлы не найдены в папке {HTML_FOLDER}")
        return

    print("=" * 70)
    print("🍽️  ПАРСЕР ИНГРЕДИЕНТОВ (с обновлением категорий)")
    print("=" * 70)
    print(f"📁 Найдено {len(html_files)} файлов")
    print("=" * 70)

    stats = {
        'total': len(html_files),
        'created': 0,
        'updated': 0,
        'skipped': 0,
        'errors': 0,
        'mapped_fields': 0,
        'total_fields': 0,
        'categories_found': 0,
        'categories_updated': 0,
        'categories_skipped': 0,
        'categories_created': 0,
    }

    for file_path in html_files:
        print(f"\n📄 Обработка: {os.path.basename(file_path)}")

        try:
            # 1. Извлекаем имя продукта
            product_name = extract_product_name(file_path)
            print(f"   🏷️  Продукт: {product_name}")

            # 2. Ищем ингредиент в базе
            ingredient = Ingredient.objects.filter(name=product_name).first()
            is_new = ingredient is None

            if is_new:
                print(f"   🆕 Новый ингредиент, создаем...")
                ingredient = Ingredient(name=product_name)
            else:
                old_category = ingredient.category.name if ingredient.category else None
                print(f"   📝 Ингредиент найден (ID: {ingredient.id})")
                if old_category:
                    print(f"   📂 Текущая категория: {old_category}")

            # 3. Читаем HTML
            with open(file_path, 'r', encoding='utf-8') as f:
                html_content = f.read()

            # 4. Извлекаем источник данных (только для новых)
            if is_new:
                data_source = extract_data_source(html_content)
                ingredient.data_source = data_source
                ingredient.description = f"Химический состав продукта '{product_name}'"
                print(f"   📚 Источник: {data_source[:80]}...")

            # 5. Парсим таблицу
            nutrients = parse_nutrients_from_table(html_content)

            if not nutrients:
                print(f"   ⚠️ Нет данных для {product_name}")
                stats['skipped'] += 1
                continue

            # 6. Обновляем поля из спарсенных данных
            updated_fields = []
            for nutrient_name, data in nutrients.items():
                # Ищем соответствие в маппинге
                field_name = None

                if nutrient_name in NUTRIENT_MAPPING:
                    field_name = NUTRIENT_MAPPING[nutrient_name]
                else:
                    for key, field in NUTRIENT_MAPPING.items():
                        if key.lower() in nutrient_name.lower() or nutrient_name.lower() in key.lower():
                            field_name = field
                            break

                if field_name:
                    # Проверяем, что поле существует в модели и не защищено
                    if hasattr(Ingredient, field_name) and field_name not in PROTECTED_FIELDS:
                        current_value = getattr(ingredient, field_name, None)
                        new_value = data['value']

                        # Обновляем только если:
                        # 1. Поле пустое (None) ИЛИ
                        # 2. Новое значение не None
                        if current_value is None or (new_value is not None and new_value != 0):
                            setattr(ingredient, field_name, new_value)
                            updated_fields.append(field_name)

            stats['mapped_fields'] += len(updated_fields)
            stats['total_fields'] += len(nutrients)

            # ========== 7. ОПРЕДЕЛЯЕМ КАТЕГОРИЮ ДЛЯ ВСЕХ ИНГРЕДИЕНТОВ ==========
            category_name = get_category_for_product(product_name)

            if category_name:
                # Ищем категорию
                category = get_or_create_category(category_name)
                if category:
                    # Проверяем, была ли уже категория
                    old_category = ingredient.category

                    # Назначаем категорию (для всех — и новых, и существующих)
                    ingredient.category = category

                    if old_category is None:
                        # У ингредиента не было категории
                        stats['categories_found'] += 1
                        if is_new:
                            print(f"   📂 Категория назначена: {category_name}")
                        else:
                            print(f"   📂 Категория добавлена: {category_name} (была пустая)")
                    elif old_category.name != category_name:
                        # Была другая категория — заменяем
                        stats['categories_updated'] += 1
                        print(f"   📂 Категория обновлена: {old_category.name} → {category_name}")
                    else:
                        # Та же категория
                        stats['categories_skipped'] += 1
                        print(f"   📂 Категория уже правильная: {category_name}")
                else:
                    print(f"   ⚠️ Не удалось найти/создать категорию: {category_name}")
            else:
                if is_new:
                    print(f"   ⚠️ Категория не определена автоматически")
                else:
                    print(f"   ⚠️ Категория не определена автоматически (оставляем существующую)")

            # 8. Сохраняем ингредиент
            ingredient.save()

            if is_new:
                stats['created'] += 1
                print(f"   ✅ Создан: {product_name} (ID: {ingredient.id})")
            else:
                stats['updated'] += 1
                print(f"   ✅ Обновлен: {product_name} (ID: {ingredient.id})")

            # Выводим информацию
            print(f"   📊 Найдено нутриентов: {len(nutrients)}, обновлено полей: {len(updated_fields)}")

            if updated_fields:
                fields_preview = ', '.join(updated_fields[:5])
                if len(updated_fields) > 5:
                    fields_preview += f" и еще {len(updated_fields) - 5}"
                print(f"   📝 Обновленные поля: {fields_preview}")

            # Показываем основные нутриенты
            main_nutrients = ['Калорийность', 'Белки', 'Жиры', 'Углеводы', 'Пищевые волокна']
            found_main = []
            for name in main_nutrients:
                if name in nutrients:
                    data = nutrients[name]
                    found_main.append(f"{name}: {data['value']} {data['unit']}")

            if found_main:
                print(f"   📊 Основные: {', '.join(found_main)}")

        except Exception as e:
            print(f"   ❌ Ошибка при обработке {file_path}: {e}")
            import traceback
            traceback.print_exc()
            stats['errors'] += 1

    # Итоговая статистика
    print("\n" + "=" * 70)
    print("📊 СТАТИСТИКА ИМПОРТА")
    print("=" * 70)
    print(f"  Всего файлов:           {stats['total']}")
    print(f"  Создано:                {stats['created']}")
    print(f"  Обновлено:              {stats['updated']}")
    print(f"  Пропущено:              {stats['skipped']}")
    print(f"  Ошибок:                 {stats['errors']}")
    print(f"  Всего нутриентов:       {stats['total_fields']}")
    print(f"  Обновлено полей:        {stats['mapped_fields']}")
    if stats['total_fields'] > 0:
        print(f"  Коэффициент:            {stats['mapped_fields'] / stats['total_fields'] * 100:.1f}%")
    print("-" * 70)
    print("📊 СТАТИСТИКА КАТЕГОРИЙ")
    print("=" * 70)
    print(f"  Категорий найдено:      {stats['categories_found']} (были пустые)")
    print(f"  Категорий обновлено:    {stats['categories_updated']} (были другие)")
    print(f"  Категорий пропущено:    {stats['categories_skipped']} (уже правильные)")
    print("=" * 70)

    if stats['errors'] > 0:
        print("\n⚠️  Внимание! Были ошибки. Проверьте логи выше.")
    else:
        print("\n✅ Импорт завершен успешно!")


if __name__ == "__main__":
    import_ingredients()