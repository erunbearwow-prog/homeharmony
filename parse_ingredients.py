def extract_product_name(filename):
    """Извлекает имя продукта из имени файла."""
    base = os.path.basename(filename)
    base = base.replace('.html', '').replace('.htm', '')
    parts = base.split('_', 2)
    if len(parts) >= 3:
        name = parts[2].strip()
        # Декодируем URL-кодировку если есть
        name = name.replace('%20', ' ').replace('%D0%B0', 'а')
        return name
    return base


def parse_nutrient_value(text):
    """Парсит значение и единицу измерения из текста."""
    if not text or text.strip() == '' or text.strip() == '~':
        return None, None

    text = text.strip().replace(',', '.')
    text = re.sub(r'(\d)\s+(\d)', r'\1\2', text)

    match = re.search(r'([\d.]+)', text)
    if not match:
        return None, None

    try:
        value = float(match.group(1))
    except ValueError:
        return None, None

    unit_match = re.search(r'([а-яА-ЯёЁ/]+)', text)
    unit = unit_match.group(1) if unit_match else ''

    return value, unit


def parse_nutrients_from_table(html_content):
    """Парсит таблицу с нутриентами."""
    soup = BeautifulSoup(html_content, 'lxml')
    table = soup.select_one('table.mzr-table.mzr-table-border.mzr-tc-chemical-table')

    if not table:
        table = soup.select_one('table.mzr-table')

    if not table:
        print("  ⚠️ Таблица не найдена!")
        return {}

    nutrients = {}
    rows = table.find_all('tr')
    current_group = None

    for row in rows:
        cols = row.find_all('td')
        if len(cols) < 2:
            continue

        first_col = cols[0].get_text(strip=True)
        if first_col == 'Нутриент':
            continue

        td = cols[0]
        is_group = 'mzr-tc-chemical-group' in td.get('class', [])

        if is_group and first_col:
            current_group = first_col
            continue

        value_text = cols[1].get_text(strip=True)
        if not value_text or value_text == '' or value_text == '~':
            continue

        value, unit = parse_nutrient_value(value_text)
        if value is None:
            continue

        nutrients[first_col] = {
            'value': value,
            'unit': unit,
            'group': current_group
        }

    return nutrients


def extract_data_source(html_content):
    """Извлекает источник данных."""
    soup = BeautifulSoup(html_content, 'lxml')
    p_tag = soup.find('p', class_='uk-h4')
    if p_tag:
        text = p_tag.get_text(strip=True)
        # Обрезаем до 500 символов (поле в БД)
        return text[:497] + '...' if len(text) > 500 else text
    return 'pbprog.ru'


def get_category_for_product(product_name):
    """
    Определяет категорию 3-го уровня для продукта по названию.
    Использует маппинг на основе вашей структуры категорий.
    """
    if not product_name:
        return None

    name_lower = product_name.lower().strip()
    # Удаляем часть в скобках для лучшего поиска
    name_clean = re.sub(r'\(.*?\)', '', name_lower).strip()

    # Проверяем по ключевым словам
    for keyword, category_name in AUTO_CATEGORY_MAPPING.items():
        if keyword in name_clean or keyword in name_lower:
            return category_name

    return None


def find_category(category_name):
    """
    Находит существующую категорию по имени.
    Возвращает объект категории или None.
    """
    if not category_name:
        return None

    category_name = category_name.strip()
    return IngredientCategory.objects.filter(name=category_name).first()


